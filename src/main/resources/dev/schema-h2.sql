CREATE TABLE IF NOT EXISTS AuditoriaExclusoes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tabela VARCHAR(100) NOT NULL,
    registro_id VARCHAR(100) NOT NULL,
    registro_descricao VARCHAR(500) NOT NULL,
    excluido_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
        ator_user_id BIGINT NOT NULL,
        ator_username VARCHAR(255) NOT NULL
    );

