CREATE TABLE IF NOT EXISTS AuditoriaExclusoes
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabela VARCHAR(100) NOT NULL,
    registro_id VARCHAR(100) NOT NULL,
    registro_descricao VARCHAR(500) NOT NULL,
    excluido_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ator_user_id BIGINT NOT NULL,
    ator_username VARCHAR(255) NOT NULL
);

CREATE OR REPLACE FUNCTION auditar_exclusao_fisica()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    registro JSONB := to_jsonb(OLD);
    ator_id BIGINT;
    ator_username TEXT;
    tabela_auditada TEXT;
    descricao_registro TEXT;
BEGIN
    ator_id := NULLIF(current_setting('app.audit_actor_id', TRUE), '')::BIGINT;
    ator_username := NULLIF(current_setting('app.audit_actor_username', TRUE), '');

    IF ator_id IS NULL OR ator_username IS NULL THEN
        RAISE EXCEPTION 'A exclusão física exige um usuário autenticado.';
    END IF;

    CASE TG_TABLE_NAME
        WHEN 'acolhidos' THEN
            tabela_auditada := 'Acolhidos';
            descricao_registro := 'Nome: ' || COALESCE(registro ->> 'nome', '');
        WHEN 'cargos' THEN
            tabela_auditada := 'Cargos';
            descricao_registro := 'Nome: ' || COALESCE(registro ->> 'nome', '');
        WHEN 'convenios' THEN
            tabela_auditada := 'Convenios';
            descricao_registro := 'Descrição: ' || COALESCE(registro ->> 'descricao', '');
        WHEN 'funcionarios' THEN
            tabela_auditada := 'Funcionarios';
            descricao_registro := 'Nome: ' || COALESCE(registro ->> 'nome', '');
        WHEN 'internacao' THEN
            tabela_auditada := 'Internacao';
            descricao_registro := 'Acolhido ID: ' || COALESCE(registro ->> 'acolhido_id', '')   || ' | Convênio ID: ' || COALESCE(registro ->> 'convenio_id', '')
                || ' | Data de entrada: ' || COALESCE(registro ->> 'data_entrada', '');
        WHEN 'medicamento' THEN
            tabela_auditada := 'Medicamento';
            descricao_registro := 'Nome: ' || COALESCE(registro ->> 'nome', '');
        WHEN 'responsaveis' THEN
            tabela_auditada := 'Responsaveis';
            descricao_registro := 'Nome: ' || COALESCE(registro ->> 'nome', '');
        WHEN 'triagem' THEN
            tabela_auditada := 'Triagem';
            descricao_registro := 'Nome possível do acolhido: ' || COALESCE(registro ->> 'nome_possivel_acolhido', '');
        WHEN 'usuarios' THEN
            tabela_auditada := 'Usuarios';
            descricao_registro := 'Username: ' || COALESCE(registro ->> 'username', '');
        ELSE
            RAISE EXCEPTION 'Tabela sem configuração de auditoria: %', TG_TABLE_NAME;
    END CASE;

    INSERT INTO AuditoriaExclusoes
        (tabela, registro_id, registro_descricao, excluido_em, ator_user_id, ator_username)
    VALUES
        (tabela_auditada, registro ->> 'id', descricao_registro, CURRENT_TIMESTAMP, ator_id, ator_username);

    RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_auditoria_delete_acolhidos ON Acolhidos;
CREATE TRIGGER trg_auditoria_delete_acolhidos AFTER DELETE ON Acolhidos FOR EACH ROW EXECUTE FUNCTION auditar_exclusao_fisica();
DROP TRIGGER IF EXISTS trg_auditoria_delete_cargos ON Cargos;
CREATE TRIGGER trg_auditoria_delete_cargos AFTER DELETE ON Cargos FOR EACH ROW EXECUTE FUNCTION auditar_exclusao_fisica();
DROP TRIGGER IF EXISTS trg_auditoria_delete_convenios ON Convenios;
